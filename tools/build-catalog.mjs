/**
 * Downloads the real star catalogue and constellation figures and writes them
 * as ES modules into data/, so the wallpaper imports them the same way it
 * imports three (no fetch(), which Lively/file:// can refuse).
 *
 *   node tools/build-catalog.mjs [limitingMagnitude=8]
 *
 * Stars:          HYG Database v4.1 (astronexus) — CC BY-SA 4.0
 * Constellations: d3-celestial (Olaf Frohn) — BSD-3-Clause
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HYG = 'https://raw.githubusercontent.com/astronexus/HYG-Database/main/hyg/CURRENT/hygdata_v41.csv';
const D3C = 'https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/';
const MAG_LIMIT = Number(process.argv[2] ?? 8);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'data');

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

// Minimal CSV line splitter: HYG quotes some fields but never embeds commas.
const split = (line) => line.split(',').map((s) => s.replace(/^"|"$/g, ''));

async function buildStars() {
  const lines = (await get(HYG)).split(/\r?\n/);
  const head = split(lines[0]);
  const col = (n) => head.indexOf(n);
  const [iRa, iDec, iMag, iCi, iProper] = ['ra', 'dec', 'mag', 'ci', 'proper'].map(col);

  const stars = [];
  for (let i = 1; i < lines.length; i++) {
    if (!lines[i]) continue;
    const f = split(lines[i]);
    if (f[iProper] === 'Sol') continue;
    const mag = Number(f[iMag]);
    if (!(mag <= MAG_LIMIT)) continue;
    const ci = f[iCi] === '' ? 0.6 : Number(f[iCi]);
    // HYG ra is in hours; store degrees.
    stars.push([Number(f[iRa]) * 15, Number(f[iDec]), mag, Number.isFinite(ci) ? ci : 0.6]);
  }
  stars.sort((a, b) => a[2] - b[2]);

  const buf = new Float32Array(stars.length * 4);
  stars.forEach((s, i) => buf.set(s, i * 4));
  const b64 = Buffer.from(buf.buffer).toString('base64');
  writeFileSync(join(out, 'stars.js'),
    `// Generated by tools/build-catalog.mjs — HYG Database v4.1 (CC BY-SA 4.0), mag <= ${MAG_LIMIT}.\n` +
    `// Float32 [raDeg, decDeg, mag, bv] per star, sorted by magnitude (brightest first).\n` +
    `export const STAR_COUNT = ${stars.length};\n` +
    `export const STARS_B64 = '${b64}';\n`);
  console.log(`stars: ${stars.length} (mag <= ${MAG_LIMIT})`);
}

async function buildConstellations() {
  const lines = JSON.parse(await get(D3C + 'constellations.lines.json'));
  const names = JSON.parse(await get(D3C + 'constellations.json'));
  const ra = (lon) => (lon + 360) % 360;

  // Flat [ra1, dec1, ra2, dec2, ...] segment list.
  const segs = [];
  for (const f of lines.features) {
    for (const poly of f.geometry.coordinates) {
      for (let i = 0; i + 1 < poly.length; i++) {
        segs.push(ra(poly[i][0]), poly[i][1], ra(poly[i + 1][0]), poly[i + 1][1]);
      }
    }
  }
  const labels = names.features.map((f) => ({
    name: f.properties.name,
    ra: +ra(f.geometry.coordinates[0]).toFixed(3),
    dec: +f.geometry.coordinates[1].toFixed(3),
  }));

  writeFileSync(join(out, 'constellations.js'),
    `// Generated by tools/build-catalog.mjs — d3-celestial constellation figures (BSD-3-Clause).\n` +
    `// SEGMENTS: flat [raDeg1, decDeg1, raDeg2, decDeg2, ...].\n` +
    `export const SEGMENTS = ${JSON.stringify(segs.map((v) => +v.toFixed(3)))};\n` +
    `export const LABELS = ${JSON.stringify(labels)};\n`);
  console.log(`constellations: ${lines.features.length} figures, ${segs.length / 4} segments, ${labels.length} labels`);
}

await buildStars();
await buildConstellations();
